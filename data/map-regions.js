function overview(name, ids, headline, summary, limits, sheets, options = {}) {
  return {
    expectedName: name,
    entities: ids.map((id) => ({ id, relation: ["xianbei", "xiongnu", "qiangHu"].includes(id) ? "activity" : "regional" })),
    kind: ids.length ? "frontier" : "uncertain",
    headline, summary, caveat: limits,
    scope: `${name}的全区域分区说明，不以首府或行政驻地替代全域`,
    evidence: "regional-overview", basis: "regional",
    dateNote: sheets.includes("16")
      ? "诸部活动分图使用 236—262 年的时期范围，不是当年单日疆界；区域综述也不等于各县已分别核实。"
      : "分图以 262 年为参照；本条从整个现代区域分区说明，仍不等于逐县、逐点实控复原。",
    sources: sheets.map((sheet) => `atlas${sheet}`),
    coverageGap: true,
    ...options,
  };
}

